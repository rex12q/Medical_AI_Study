import numpy as np
from sklearn.linear_model import LogisticRegression
#sklearn(scikit-learn)머신러닝 도구들이 잔뜩 들어있는 상자
#linear_model은 컴퓨터가 그은 선으로 데이터의 참'/(=선)'거짓을 판단하는 경계.(Decision Boundary)
#LogisticRegression 분류기 역할, 맞다/아니다 또는 질병 있음/ 없음..등 둘 중 하나를 고르는 모델, 2차원 배열까지만 받는다.
#연계:sklearn상자에서 참과 거짓을 구분할 선을 그어줄linear_model을 꺼내고 LogisticRegression로 참/거짓 중 하나를 고른다
print('공부용 데이터로 만든 당뇨 위험 예측 (공부용)')

#np선언 array:배열
#X=[나이,BMI] (가짜 데이터 제공)
X=np.array ([
    [25, 20.0],
    [30, 22.0],
    [35, 24.0],
    [40, 26.0],
    [45, 28.0],
    [50, 30.0],
    [55, 32.0],
    [60, 34.0],
]) 

#Y=당뇨 여부(0=거짓, 1=참) (가짜 데이터 제공)
Y=np.array([0,0,0,0,1,1,1,1])

#여기서의 model은 의사처럼 판단해주는 AI이다
#위 데이터 가져와서 판단하기!
model=LogisticRegression()#판단할 의사 틀 만들어줌
model.fit(X,Y)#여기서 '학습'을 하고 'fit'은 경험을 쌓아서 판단 기준을 만든다. 데이터에 맞게 기준을 정함
#위에 있는 데이터들을 가지고 판단 기준을 스스로 학습(적응)하는 과정
#예시로 나이 25에 bmi수치 20인 사람은 당뇨 여부가 거짓이기에 0/ 나이 45에 bmi수치 28인 사람은 당뇨 여부가 참이기에 1 
#이러한 데이터들을 가지고 fit이라는 머신러닝 모델이 학습을 하면 bmi수치 중요도(가중치=w)가 높아지고 별 영향 없는 변수(나이)의 중요도(가중치=w)는 낮아짐 
print('모델 학습 완료!')

#새 사용자 정보 입력 받기
age=int(input('나이를 입력하세요.'))
bmi=float(input('bmi수치를 입력해주세요'))

#머신러닝은 '여려 명의 데이터' 형태로 받도록 설계됨, 그래서 1명이어도 이렇게 쓰임
# 위에서 이미 0=당뇨 여부x(병없음) 1=당뇨 여부o(병있음)로 사용자가 둠 여기서 [0]은  
#([[]]) 사람 여러 명 중 한 명이라도 "헹렬 형태"로 만들기 위해서 
#[
#[10, 20, 30], 
#] <-2차원을 나타냄
new_data=np.array([[age,bmi]]) #2차원 생성 LogisticRegression은 2차원까지만 받음
predict1=model.predict(new_data)[0] #[]이중으로 쓸 시 3차원 생성 -> 오류
#파이썬에서 데이터의 위치를 셀 때는 무조건 0부터 시작한다. 행열로 0은 첫번째 행, 모델이 예측한 사람은 단 한 명 (new data), 따라서 0은 첫번째 사람에 대한 예측 결과 줄을 선택
prob=model.predict_proba(new_data)[0][1]
#0은 첫번째 사람을 의미, 1은 질병일 확률(여기서 0,1이 쪼개지는데 앞전에 쓰인 0이랑은 완전히 다른 인덱스다) 0(1빠따),0(음성),1(양성)
#첫번째 사람(입력한 사용자)의 정보가 양성일 확률을 가져와라  

print(f'모델이 예측한 당뇨 위험 여부 (0:x,1:o): {predict1}')
print(f'당뇨일 확률(모델 관점): {prob*100:.6f}%')
print('해당 모델은 가짜 데이터로 만든 학습용입니다. 실제 의료 판단에 절대 쓰지 마세요.')

#array detail comment
# 배열을 의미한다. 숫자나 문자 등의 데이터를 일렬로 나열한 구조이다 [1,2,3,4,5] 배열을 구조화하면 연산에 효과가 있으며 같은 타입(원소)으로 구성되어 있어 메모리 사용에 효율적

#Machine Learning 2d Array detail comment
# 앞서 코드와 함께 언급했다 ml은 2차원 배열을 구조로 띄며, 만약 사용자가 대괄호 하나만 썼을 경우 ml은 오류를 출력한다
# 오류의 원인은 사용자가 입력한 독립변수(x)가 어떤 걸 의미하는 지 알 수가 없기 때문이다 사용자는 bmi와 나이를 입력했다면 모델은 나이와 bmi를 두 사람이라고 착각할 수도 있다
# 그게 아니면 오직 환자 1인의 나이와 bmi인 지 구분하기가 힘들다/ 해결: 대괄호를 2개를 써야 한다 그래야 사용자의 정보(나이,bmi)를 한 번에 분석할 수 있기 떄문이다
# 즉 한 명의 환자에 두개의 '특성'이 들어있다고 보면 편하다(shape를 써서 보면 알 수 있다)

#linear_model detail comment 
#결정 경계(Decision Boundary)를 생성한다. 사용자의 입력 값이 true or false인지를 구분하기 위해 경계를 생성한다. Regression은 true and false 사이의 가장 완벽한 직선을 긋는다
#예를 들어 직선 하나를 그어서 경계를 생성하면 true or false를 구분할 수 있다. (x축을 나이, y축을 bmi) 이 선을 기준으로 시그모이드 함수가 중간인 0.5보다 작은지 큰지 판가름 할 수 있다
#Decision Boundary 선을 기준으로 한참 선 위에 있으면 참일 확률이 매우 높다는 것이다| 반대로 선을 기준으로 한참 선 아래에 있으면 거짓일 확률이 매우 높다는 것이다| 가장 중간에 있는 정보들은 50프로 정도에 머물러있다
#애해만 경우 50프로 정도를 출력하며 경게선 주변에 있는 정보들은 (참일 경우: 50,51,52...)|(거짓일 경우: 50,49,48...)

# Regression detail comment 
# 회귀는 독립변수(x)와 종속변수(y)로 이루어진 식이다 예를 들어 y=ax+b라고 식을 짰을 때 우리가 원하는 결과값(y)와 저 종속변수를 책임져줄 독립변수(x)랑 가중치(w)인(a)
# 그리고 b는 y절편(기본적으로 x가 0이어도 깔고 가는 값) 이것이 단순 회귀이고 여기서 더 복잡한(나이와 bmi를 동시 입력) 조건이 나오면 그만큼의 가중치와 독립변수를 쓰면 된다
# LogisticRegression detail comment
# 시그모이드 함수가 포함된다. 의료 ai에서는 환자의 당뇨병을 판정하기 위해 0과 1사이의 확률값이 나온다. 단순 회귀(z)는 결과가 그대로 나오고 논리 회귀(sigmoid z)는 0과 1사이 
#시그모이드 작동 원리: sigmoid=1/1+e^-z (e:자연상수(2.718예상)), 지수 z:입력값 회귀 결과) 0과 1사이에 값이 나오도록 한다.
#
#EXAMPLE
#해당 식에는 -가 있으므로 1/e^z랑 동일하며, 2.718에 제곱(z가 2라는 것을 가정)을 하여 1/7.389가 나오며 1을 7.389로 나누면 0.135가 나온다 앞서 식에 1+가 있기에 1/1.135
#즉 1/1.135는 0.88이다 

